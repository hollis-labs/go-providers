package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hollis-labs/go-providers/layout"
)

const (
	docPath  = "docs/LAYOUT.md"
	jsonPath = "layout/layout.json"
)

func main() {
	check := flag.Bool("check", false, "fail when the generated files are stale instead of writing them")
	root := flag.String("root", "", "module root (default: nearest directory with go.mod)")
	flag.Parse()
	if *root == "" {
		r, err := findRoot()
		if err != nil {
			fmt.Fprintln(os.Stderr, "layout/gen:", err)
			os.Exit(2)
		}
		*root = r
	}
	stale, err := run(*root, *check)
	if err != nil {
		fmt.Fprintln(os.Stderr, "layout/gen:", err)
		os.Exit(2)
	}
	if len(stale) > 0 {
		fmt.Fprintf(os.Stderr, "layout/gen: stale: %s (run: go generate ./...)\n", strings.Join(stale, ", "))
		os.Exit(1)
	}
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory; pass -root")
		}
		dir = parent
	}
}

// run writes (or, with check, compares) the generated files under root and
// returns the paths that differ.
func run(root string, check bool) ([]string, error) {
	outputs, err := render(layout.Table())
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, rel := range []string{docPath, jsonPath} {
		want := outputs[rel]
		full := filepath.Join(root, filepath.FromSlash(rel))
		got, readErr := os.ReadFile(full)
		if readErr == nil && bytes.Equal(got, want) {
			continue
		}
		if check {
			stale = append(stale, rel)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(full, want, 0o644); err != nil {
			return nil, err
		}
	}
	return stale, nil
}

func render(table []layout.Entry) (map[string][]byte, error) {
	j, err := json.MarshalIndent(struct {
		Schema  int            `json:"schema"`
		Entries []layout.Entry `json:"entries"`
	}{Schema: 1, Entries: table}, "", "  ")
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		docPath:  []byte(markdown(table)),
		jsonPath: append(j, '\n'),
	}, nil
}

func markdown(table []layout.Entry) string {
	var b strings.Builder
	b.WriteString("# Provider layout\n\n")
	b.WriteString("<!-- Code generated by go run ./layout/gen; DO NOT EDIT. Source: layout/table.go -->\n\n")
	b.WriteString("Where each agent CLI reads its files, skills and config, relative to which launch root, and the flag, environment and working directory that locate them. ")
	b.WriteString("Every row cites the Step 0 probe ids that measured it (see [HARNESS-DISCOVERY.md](HARNESS-DISCOVERY.md)); rows with no probe say why. ")
	b.WriteString("An empty mode means every mode of the provider; a mode-specific row overrides the every-mode row of the same concern. ")
	b.WriteString("Skills are placed in the directory form `<rel>/<name>/SKILL.md` only.\n")
	var providers []layout.Provider
	seen := map[layout.Provider]bool{}
	for _, e := range table {
		if !seen[e.Provider] {
			seen[e.Provider] = true
			providers = append(providers, e.Provider)
		}
	}
	for _, p := range providers {
		fmt.Fprintf(&b, "\n## %s\n\n", p)
		b.WriteString("| mode | concern | root | rel | form | file mode | flag | env | cwd | aliases | probe | note |\n")
		b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|---|\n")
		for _, e := range table {
			if e.Provider != p {
				continue
			}
			probe := strings.Join(e.Probe, ", ")
			note := e.Note
			if e.Unprobed != "" {
				probe = "none"
				if note != "" {
					note += " "
				}
				note += "Unprobed: " + e.Unprobed + "."
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				cell(string(e.Mode), "all"), e.Concern, e.Root, code(e.Rel), cell(string(e.Form), ""),
				fileMode(e.FileMode), code(e.Flag), envCell(e.Env), cell(string(e.CWD), ""),
				cell(strings.Join(e.Aliases, ", "), ""), probe, escape(note))
		}
	}
	return b.String()
}

func cell(v, empty string) string {
	if v == "" {
		return empty
	}
	return escape(v)
}

func code(v string) string {
	if v == "" {
		return ""
	}
	return "`" + escape(v) + "`"
}

func fileMode(m uint32) string {
	if m == 0 {
		return ""
	}
	return fmt.Sprintf("%04o", m)
}

func envCell(env map[string]string) string {
	keys := make([]string, 0, len(env))
	for k := range env {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("`%s=<%s>`", k, env[k]))
	}
	return strings.Join(parts, "<br>")
}

func escape(v string) string {
	r := strings.NewReplacer("|", `\|`, "\n", " ", "<", "&lt;", ">", "&gt;")
	return r.Replace(v)
}
